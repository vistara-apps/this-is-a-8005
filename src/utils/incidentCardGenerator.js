// Utility for generating shareable incident cards
import { IncidentCard } from '../data/models.js'
import { getStateRights, getDefaultRightsGuide } from '../data/stateRightsData.js'
import { openaiService } from '../services/openaiService.js'

/**
 * Generate a shareable incident card
 * @param {IncidentRecord} incidentRecord - The incident record
 * @param {Object} userState - User's state information
 * @param {Array} emergencyContacts - Emergency contacts
 * @returns {Promise<IncidentCard>} Generated incident card
 */
export async function generateIncidentCard(incidentRecord, userState = '', emergencyContacts = []) {
  try {
    // Get state-specific rights information
    const stateRights = getStateRights(userState) || getDefaultRightsGuide(userState)
    
    // Extract key rights information
    const rightsInfo = {
      state: userState,
      keyRights: [
        'You have the right to remain silent',
        'You have the right to refuse consent to searches',
        'You have the right to an attorney',
        'You have the right to record police interactions in public'
      ],
      stateSpecific: stateRights.dosDonts.dos.slice(0, 3), // Top 3 dos
      emergencyNumbers: [
        { name: 'Emergency Services', number: '911' },
        { name: 'ACLU Legal Hotline', number: '1-877-6-PROFILE' }
      ]
    }

    // Generate AI description if available
    let description = `Police interaction documented on ${new Date(incidentRecord.timestamp).toLocaleDateString()}`
    if (openaiService.isAvailable()) {
      try {
        description = await openaiService.generateIncidentDescription(incidentRecord)
      } catch (error) {
        console.warn('Failed to generate AI description:', error)
      }
    }

    // Create the incident card
    const incidentCard = new IncidentCard({
      recordId: incidentRecord.recordId,
      location: incidentRecord.location,
      timestamp: incidentRecord.timestamp,
      rightsInfo: rightsInfo,
      emergencyContacts: emergencyContacts,
      shareableUrl: null // Will be set when shared
    })

    // Add description to metadata
    incidentCard.description = description

    return incidentCard
  } catch (error) {
    console.error('Error generating incident card:', error)
    throw new Error('Failed to generate incident card')
  }
}

/**
 * Generate a text summary for sharing
 * @param {IncidentCard} incidentCard - The incident card
 * @returns {string} Text summary
 */
export function generateTextSummary(incidentCard) {
  const date = new Date(incidentCard.timestamp).toLocaleString()
  const location = incidentCard.location 
    ? `Location: ${formatLocation(incidentCard.location)}`
    : 'Location: Not specified'

  return `🚨 POLICE INTERACTION DOCUMENTED 🚨

${incidentCard.description || 'Police interaction documented'}

📅 Date/Time: ${date}
📍 ${location}

🛡️ KNOW YOUR RIGHTS:
${incidentCard.rightsInfo.keyRights.map(right => `• ${right}`).join('\n')}

📞 EMERGENCY CONTACTS:
${incidentCard.rightsInfo.emergencyNumbers.map(contact => `• ${contact.name}: ${contact.number}`).join('\n')}

Generated by Know Your Rights Buddy
#KnowYourRights #PoliceAccountability #CivilRights`
}

