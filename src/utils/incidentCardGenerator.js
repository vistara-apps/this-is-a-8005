/**
 * Format location for display
 * @param {Object|string} location - Location data
 * @returns {string} Formatted location
 */
function formatLocation(location) {
  if (typeof location === 'string') {
    return location
  }

  if (location && typeof location === 'object') {
    if (location.latitude && location.longitude) {
      return `${location.latitude.toFixed(6)}, ${location.longitude.toFixed(6)}`
    }
    if (location.address) {
      return location.address
    }
    if (location.city && location.state) {
      return `${location.city}, ${location.state}`
    }
  }

  return 'Location recorded'
}

/**
 * Create a shareable URL for the incident card
 * @param {IncidentCard} incidentCard - The incident card
 * @returns {string} Shareable URL
 */
export function createShareableURL(incidentCard) {
  const baseUrl = window.location.origin
  const cardData = encodeURIComponent(JSON.stringify({
    id: incidentCard.cardId,
    timestamp: incidentCard.timestamp,
    location: incidentCard.location,
    description: incidentCard.description
  }))
  
  return `${baseUrl}/incident/${incidentCard.cardId}?data=${cardData}`
}

/**
 * Share incident card via Web Share API or fallback
 * @param {IncidentCard} incidentCard - The incident card
 * @returns {Promise<boolean>} Share success status
 */
export async function shareIncidentCard(incidentCard) {
  const textSummary = generateTextSummary(incidentCard)
  const shareableUrl = createShareableURL(incidentCard)

  // Try Web Share API first
  if (navigator.share) {
    try {
      await navigator.share({
        title: 'Police Interaction Documentation',
        text: textSummary,
        url: shareableUrl
      })
      return true
    } catch (error) {
      if (error.name !== 'AbortError') {
        console.error('Web Share API failed:', error)
      }
    }
  }

  // Fallback to clipboard
  try {
    await navigator.clipboard.writeText(`${textSummary}\n\n${shareableUrl}`)
    return true
  } catch (error) {
    console.error('Clipboard API failed:', error)
    return false
  }
}
